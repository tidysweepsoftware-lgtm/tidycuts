/// What a sticker drawing gets.
pub struct DrawCtx {
    pub w: f32,
    pub h: f32,
    pub color: [f32; 4],
    pub color2: [f32; 4],
    /// Seconds, for animated stickers.
    pub t: f32,
    /// Which look of the drawing to make (0 for the first). A drawing used
    /// for several catalog items reads this to pick its font, layout or
    /// options.
    pub variant: u32,
}

#[derive(Clone, Copy)]
pub struct StickerDef {
    pub id: &'static str,
    pub name: &'static str,
    pub category: &'static str,
    pub color: [f32; 4],
    pub color2: [f32; 4],
    /// Default looping motion (see `animations::sticker_motion`).
    pub motion: &'static str,
    /// Width / height.
    pub aspect: f32,
    /// Redrawn every frame (particles, sparkles…) rather than once.
    pub animated: bool,
    /// The look of the shared drawing this item uses (see `DrawCtx`).
    pub variant: u32,
    pub draw: fn(&mut Pixmap, &DrawCtx),
}

/// Natural sticker height in project pixels for a 1080p frame.
pub const STICKER_HEIGHT: f32 = 320.0;

const W: [f32; 4] = [1.0, 1.0, 1.0, 1.0];
const INK: [f32; 4] = [0.12, 0.12, 0.16, 1.0];

const fn c(r: f32, g: f32, b: f32) -> [f32; 4] {
    [r, g, b, 1.0]
}

#[allow(clippy::too_many_arguments)]
const fn s(
    id: &'static str,
    name: &'static str,
    category: &'static str,
    color: [f32; 4],
    color2: [f32; 4],
    motion: &'static str,
    aspect: f32,
    draw: fn(&mut Pixmap, &DrawCtx),
) -> StickerDef {
    StickerDef {
        id,
        name,
        category,
        color,
        color2,
        motion,
        aspect,
        animated: false,
        variant: 0,
        draw,
    }
}

const fn animated(mut d: StickerDef) -> StickerDef {
    d.animated = true;
    d
}

/// Another catalog item made from the same drawing as `base`: its own id,
/// name, starting colours and picture proportions, and a `variant` number
/// the drawing reads. One design, many stickers.
#[allow(clippy::too_many_arguments)]
const fn variant(
    base: StickerDef,
    id: &'static str,
    name: &'static str,
    variant: u32,
    color: [f32; 4],
    color2: [f32; 4],
    aspect: f32,
) -> StickerDef {
    StickerDef {
        id,
        name,
        color,
        color2,
        aspect,
        variant,
        ..base
    }
}

