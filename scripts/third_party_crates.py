#!/usr/bin/env python3
"""Writes docs/third-party-crates.md: every Rust library TidyCuts is built
with, its version and its licence, from `cargo metadata`.

    python3 scripts/third_party_crates.py
"""
import json
import subprocess
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
meta = json.loads(
    subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root
    )
)
workspace = set(meta["workspace_members"])
rows = sorted(
    (p["name"], p["version"], p.get("license") or "see the crate", p.get("repository") or "")
    for p in meta["packages"]
    if p["id"] not in workspace
)
out = [
    "# Libraries TidyCuts is built with",
    "",
    "Generated by `scripts/third_party_crates.py` from `Cargo.lock`. Every one is",
    "under a permissive licence (MIT, Apache-2.0, BSD, Zlib, ISC, Unicode and",
    "similar). Where a library offers a choice (`A OR B`), TidyCuts uses it under",
    "the permissive one.",
    "",
    "| Library | Version | Licence |",
    "| --- | --- | --- |",
]
for name, version, lic, repo in rows:
    label = f"[{name}]({repo})" if repo else name
    out.append(f"| {label} | {version} | {lic} |")
out.append("")
(root / "docs" / "third-party-crates.md").write_text("\n".join(out))
print(f"{len(rows)} libraries written to docs/third-party-crates.md")
